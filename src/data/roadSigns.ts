export const roadSignById: Record<string, RoadSign> = Object.fromEntries(roadSigns.map((sign) => [sign.id, sign]));

export function searchRoadSigns(query: string, category: RoadSignCategory | 'alla' = 'alla') {
  const needle = query.trim().toLocaleLowerCase('sv');
  return roadSigns.filter((sign) => {
    if (category !== 'alla' && sign.category !== category) return false;
    if (!needle) return true;
    return `${sign.nameSv} ${sign.meaning} ${sign.officialCode ?? ''}`.toLocaleLowerCase('sv').includes(needle);
  });
}
